/**
 * حجم بديل لعنصر (صغير/وسط/كبير) — كل حجم بماكروزه التقديرية الخاصة وغراماته،
 * حتى يسجّل المستخدم الحجم الفعلي الذي طلبه بدل تقدير واحد فقط.
 */
export interface FoodSize {
  id: string
  labelAr: string
  labelEn: string
  servingLabelAr: string
  servingGrams: number
  calories: number
  protein: number
  carbs: number
  fat: number
}

export interface FoodItem {
  id: string
  nameAr: string
  nameEn: string
  category: FoodCategory
  servingLabelAr: string
  servingGrams?: number
  calories: number
  protein: number
  carbs: number
  fat: number
  fiber?: number
  notesAr?: string
  /** كلمات بحث إضافية (أسماء سلاسل/مطاعم وكتابات بديلة) لتسهيل الإيجاد */
  keywords?: string[]
  /**
   * أحجام بديلة (صغير/وسط/كبير) — القيم العليا للعنصر تمثّل الحجم الوسط (الافتراضي)،
   * وهذه القائمة تتيح اختيار الحجم الفعلي بماكروزه الخاصة عند التسجيل.
   */
  sizes?: FoodSize[]
}

