export const foodMap: Record<string, FoodItem> = Object.fromEntries(
  foodItems.map((f) => [f.id, f]),
)

export function getFood(id: string): FoodItem | undefined {
  return foodMap[id]
}

export function searchFood(query: string): FoodItem[] {
  const q = query.trim().toLowerCase()
  if (!q) return foodItems
  return foodItems.filter(
    (f) =>
      f.nameAr.toLowerCase().includes(q) || f.nameEn.toLowerCase().includes(q),
  )
}
