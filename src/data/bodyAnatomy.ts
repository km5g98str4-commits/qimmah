// ============================================================================
// تشريح الجسم — رسم SVG أصليّ لجسم رياضيّ واقعيّ (أمامي/خلفي) واعٍ بالجنس.
// لوحة العرض: 0 0 220 470، ومركز الجسم أفقيًا x = 110.
// الفلسفة: قوام V رياضي — أكتاف عريضة، خصر منحوت، عضلات معرّفة بمنحنيات
// تشريحية (لا أشكال بيضاوية طفولية). الرأس مجرّد (بلا ملامح) لتفادي أي حقوق
// وللإبقاء على مظهر نظيف. الجانب الأيسر يُرسم يدويًا ويُعكس آليًا للأيمن،
// ما يضمن تماثلًا دقيقًا ويقلّل التكرار. كل الأبعاد مشتقّة من نِسَب الجنس.
// ============================================================================

/** محور التماثل الأفقي (مركز×2): العكس x' = 220 − x. */
const AXIS2 = 220

/** المركز الأفقي للجسم. */
const CX = 110

/**
 * يعكس مسار SVG أفقيًا حول مركز اللوحة.
 * يدعم الأوامر المطلقة M L C Q T S Z (أزواج إحداثيات x,y) — تُقلب قيم x فقط.
 */
export function mirrorPath(d: string): string {
  const tokens = d.match(/[a-zA-Z]|-?\d*\.?\d+/g) ?? []
  const out: string[] = []
  let coordIndex = 0
  for (const tok of tokens) {
    if (/[a-zA-Z]/.test(tok)) {
      out.push(tok)
      coordIndex = 0 // كل أمر يبدأ سلسلة أزواج (x,y) جديدة
      continue
    }
    const n = parseFloat(tok)
    // الفهرس الزوجي = x فيُعكس، الفردي = y فيبقى.
    out.push(coordIndex % 2 === 0 ? round(AXIS2 - n) : tok)
    coordIndex++
  }
  let res = ''
  for (const t of out) {
    if (/[a-zA-Z]/.test(t)) res += (res ? ' ' : '') + t
    else res += ' ' + t
  }
  return res.trim()
}

/** تقريب رقمي مرتّب (يتجنّب أخطاء الفاصلة العائمة الطويلة). */
function round(n: number): string {
  return String(Math.round(n * 100) / 100)
}

