// الملابس الرياضية المحتشمة — طبقة تُرسم فوق العضلات.
// شفافة جزئيًا كي يظهر تلوين العضلة المُدرَّبة من خلالها، مع حدود واضحة
// تؤكّد وجود اللباس. للأنثى: توب رياضي + شورت ساتر. للذكر: شورت فقط.
// ============================================================================

export interface Garment {
  d: string
  /** صلب = حشوة كاملة، شفّاف = حشوة جزئية تُظهر العضلة. */
  opacity: number
}

/** يبني طبقة اللباس حسب الجنس وجهة العرض. */
export function buildClothing(gender: Gender, view: MuscleView): Garment[] {
  const cx = 110
  const p = PROPS[gender]
  const items: Garment[] = []

  if (gender === 'female') {
    if (view === 'front') {
      // توب رياضي يغطّي الصدر بالكامل بحياء، بحمّالات على الكتف.
      items.push({
        d:
          `M${cx - 26} 80 ` +
          `C${cx - 28} 96 ${cx - 26} 112 ${cx - 22} 122 ` +
          `C${cx - 10} 128 ${cx + 10} 128 ${cx + 22} 122 ` +
          `C${cx + 26} 112 ${cx + 28} 96 ${cx + 26} 80 ` +
          `C${cx + 14} 86 ${cx - 14} 86 ${cx - 26} 80 Z`,
        opacity: 0.55,
      })
      // حمّالتا الكتف.
      items.push({ d: `M${cx - 24} 80 L${cx - 18} 78 L${cx - 15} 90 L${cx - 21} 92 Z`, opacity: 0.55 })
      items.push({ d: `M${cx + 24} 80 L${cx + 18} 78 L${cx + 15} 90 L${cx + 21} 92 Z`, opacity: 0.55 })
      // شورت رياضي ساتر يغطّي الورك وأعلى الفخذ.
      items.push({
        d:
          `M${cx - p.hip - 1} 178 ` +
          `C${cx - p.hip - 1} 196 ${cx - p.hip + 3} 214 ${cx - 14} 222 ` +
          `L${cx - 3} 222 L${cx - 3} 200 L${cx + 3} 200 L${cx + 3} 222 ` +
          `L${cx + 14} 222 ` +
          `C${cx + p.hip - 3} 214 ${cx + p.hip + 1} 196 ${cx + p.hip + 1} 178 ` +
          `C${cx + 14} 186 ${cx - 14} 186 ${cx - p.hip - 1} 178 Z`,
        opacity: 0.55,
      })
    } else {
      // ظهر التوب الرياضي + حمّالات متقاطعة.
      items.push({
        d:
          `M${cx - 26} 80 ` +
          `C${cx - 28} 96 ${cx - 26} 110 ${cx - 22} 118 ` +
          `C${cx - 10} 122 ${cx + 10} 122 ${cx + 22} 118 ` +
          `C${cx + 26} 110 ${cx + 28} 96 ${cx + 26} 80 ` +
          `C${cx + 14} 86 ${cx - 14} 86 ${cx - 26} 80 Z`,
        opacity: 0.55,
      })
      items.push({ d: `M${cx - 22} 84 L${cx + 18} 104 L${cx + 15} 110 L${cx - 25} 90 Z`, opacity: 0.5 })
      items.push({ d: `M${cx + 22} 84 L${cx - 18} 104 L${cx - 15} 110 L${cx + 25} 90 Z`, opacity: 0.5 })
      // شورت ساتر يغطّي الألوية بالكامل.
      items.push({
        d:
          `M${cx - p.hip - 1} 176 ` +
          `C${cx - p.hip - 1} 198 ${cx - p.hip + 2} 218 ${cx - 12} 226 ` +
          `L${cx} 224 L${cx + 12} 226 ` +
          `C${cx + p.hip - 2} 218 ${cx + p.hip + 1} 198 ${cx + p.hip + 1} 176 ` +
          `C${cx + 14} 184 ${cx - 14} 184 ${cx - p.hip - 1} 176 Z`,
        opacity: 0.6,
      })
    }
    return items
  }

  // الذكر / غير المحدّد: شورت رياضي يغطّي الورك وأعلى الفخذ (الجذع مكشوف كمخطّط تشريحي).
  if (view === 'front') {
    items.push({
      d:
        `M${cx - p.hip - 1} 176 ` +
        `C${cx - p.hip - 1} 194 ${cx - p.hip + 3} 210 ${cx - 14} 218 ` +
        `L${cx - 3} 218 L${cx - 3} 198 L${cx + 3} 198 L${cx + 3} 218 ` +
        `L${cx + 14} 218 ` +
        `C${cx + p.hip - 3} 210 ${cx + p.hip + 1} 194 ${cx + p.hip + 1} 176 ` +
        `C${cx + 14} 184 ${cx - 14} 184 ${cx - p.hip - 1} 176 Z`,
      opacity: 0.6,
    })
  } else {
    items.push({
      d:
        `M${cx - p.hip - 1} 174 ` +
        `C${cx - p.hip - 1} 196 ${cx - p.hip + 2} 214 ${cx - 12} 222 ` +
        `L${cx} 220 L${cx + 12} 222 ` +
        `C${cx + p.hip - 2} 214 ${cx + p.hip + 1} 196 ${cx + p.hip + 1} 174 ` +
        `C${cx + 14} 182 ${cx - 14} 182 ${cx - p.hip - 1} 174 Z`,
      opacity: 0.6,
    })
  }
  return items
}
