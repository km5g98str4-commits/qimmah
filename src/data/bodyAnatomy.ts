// ============================================================================
// تشريح الجسم — أشكال SVG لجسم بشري عضلي واقعي (أمامي/خلفي) واعٍ بالجنس.
// لوحة الرسم 0 0 220 470، مركز الجسم أفقيًا x=110، الركبة عند y≈310.
// كل عضلة مرسومة كمسار/مسارات (paths) بمنحنيات تشريحية متجاورة تملأ سطح الجسم
// (لا فقاعات صغيرة عائمة) لتعطي مظهرًا عضليًا حقيقيًا كخريطة تشريح.
// الجوانب اليسرى تُرسم يدويًا وتُعكس آليًا (mirrorPath) لإنتاج الجانب الأيمن.
//
// الاحتشام (جمهور سعودي): شورت رياضي يغطّي حتى الركبة، وحزام الشورت يستر
// السرّة/أسفل البطن. الأنثى ترتدي توبًا رياضيًا يستر الصدر والوسط بالكامل +
// شورت حتى الركبة. عضلات الذراعين/الأكتاف/الساقين/الجذع الظاهر تتلوّن عند التمرين،
// وما تحت اللباس الشفّاف جزئيًا يظهر تلوينه مكتومًا من خلال القماش.
// ============================================================================

/** محور التماثل الأفقي (مركز×2): العكس x' = 220 − x. */
const AXIS2 = 220

/**
 * يعكس مسار SVG أفقيًا حول مركز اللوحة.
 * يدعم فقط الأوامر المطلقة M L C Q T S Z (إحداثيات أزواج x,y) — تُقلب قيم x.
 */
export function mirrorPath(d: string): string {
  const tokens = d.match(/[a-zA-Z]|-?\d*\.?\d+/g) ?? []
  const out: string[] = []
  let coordIndex = 0
  for (const tok of tokens) {
    if (/[a-zA-Z]/.test(tok)) {
      out.push(tok)
      coordIndex = 0 // كل أمر يبدأ سلسلة أزواج (x,y) جديدة
      continue
    }
    const n = parseFloat(tok)
    // الفهرس الزوجي = x فيُعكس، الفردي = y فيبقى.
    out.push(coordIndex % 2 === 0 ? String(AXIS2 - n) : String(n))
    coordIndex++
  }
  // إعادة تجميع: حرف ثم أرقامه مفصولة بمسافات.
  let res = ''
  for (const t of out) {
    if (/[a-zA-Z]/.test(t)) res += (res ? ' ' : '') + t
    else res += ' ' + t
  }
  return res.trim()
}

/** عضلة قابلة للاختيار = معرّفها + مسار/مسارات رسمها. */
export interface BodyRegion {
  m: MuscleId
  d: string[]
}

/** زوج يسار/يمين من مسار الجانب الأيسر. */
const pair = (left: string): string[] => [left, mirrorPath(left)]

// ============================================================================
// الأجزاء المحايدة (الهيكل الجلدي): رأس/رقبة/جذع/ذراعان/ساقان/يدان/قدمان.
// تُرسم بلون البشرة خلف العضلات لتعطي الجسم حدوده. تتغيّر أبعادها حسب الجنس
// لإنتاج مظهر V رياضي للذكر ومظهر منحوت رياضي للأنثى.
// ============================================================================

interface Proportions {
  shoulder: number // نصف عرض الكتف
  waist: number // نصف عرض الخصر
  hip: number // نصف عرض الورك
  neck: number // نصف عرض الرقبة
}

const PROPS: Record<Gender, Proportions> = {
  // ذكر: أكتاف عريضة، خصر منحوت (مظهر V عضلي).
  male: { shoulder: 52, waist: 26, hip: 33, neck: 12 },
  // أنثى: أكتاف أضيق، خصر أنحف، ورك أوسع (مظهر رياضي أنثوي).
  female: { shoulder: 43, waist: 20, hip: 37, neck: 9 },
  // غير محدّد: وسط بين الاثنين.
  unspecified: { shoulder: 47, waist: 23, hip: 33, neck: 10 },
}

/** يبني مسارات الهيكل الجلدي المحايد لجهة العرض. */
export function buildSilhouette(gender: Gender, view: MuscleView): string[] {
  const p = PROPS[gender]
  const cx = 110
  const sh = p.shoulder
  const w = p.waist
  const hip = p.hip
  const nk = p.neck

  // الرأس + الرقبة (مشتركة بين الجهتين).
  const head = `M${cx} 12 C${cx - 16} 12 ${cx - 22} 20 ${cx - 22} 32 C${cx - 22} 44 ${cx - 15} 58 ${cx} 58 C${cx + 15} 58 ${cx + 22} 44 ${cx + 22} 32 C${cx + 22} 20 ${cx + 16} 12 ${cx} 12 Z`
  const neck = `M${cx - nk} 53 L${cx + nk} 53 L${cx + nk + 1} 74 L${cx - nk - 1} 74 Z`

  // الجذع: كتف عريض → خصر منحوت → ورك، بمنحنيات عضلية.
  const torso =
    `M${cx - sh} 80 ` +
    `C${cx - sh - 2} 98 ${cx - w - 6} 126 ${cx - w} 150 ` +
    `C${cx - w + 1} 168 ${cx - hip} 178 ${cx - hip} 196 ` +
    `L${cx + hip} 196 ` +
    `C${cx + hip} 178 ${cx + w - 1} 168 ${cx + w} 150 ` +
    `C${cx + w + 6} 126 ${cx + sh + 2} 98 ${cx + sh} 80 ` +
    `C${cx + sh - 10} 70 ${cx - sh + 10} 70 ${cx - sh} 80 Z`

  // الذراع الأيسر: كتف → انتفاخ العضد → ساعد متناقص (يُعكس للأيمن).
  const armL =
    `M${cx - sh + 2} 82 ` +
    `C${cx - sh - 9} 96 ${cx - sh - 11} 124 ${cx - sh - 8} 150 ` +
    `C${cx - sh - 7} 178 ${cx - sh - 4} 198 ${cx - sh - 1} 206 ` +
    `C${cx - sh + 9} 206 ${cx - sh + 13} 200 ${cx - sh + 13} 192 ` +
    `C${cx - sh + 12} 150 ${cx - sh + 14} 110 ${cx - sh + 10} 84 Z`

  // اليد اليسرى (كتلة عند نهاية الساعد).
  const handL = `M${cx - sh - 1} 204 C${cx - sh - 5} 210 ${cx - sh - 4} 224 ${cx - sh + 3} 226 C${cx - sh + 11} 226 ${cx - sh + 15} 218 ${cx - sh + 13} 206 Z`

  // الساق اليسرى: فخذ ممتلئ → ركبة (y≈312) → ساق سفلية → كاحل.
  const legL =
    `M${cx - hip} 196 ` +
    `C${cx - hip - 1} 240 ${cx - hip + 5} 286 ${cx - 24} 312 ` +
    `C${cx - 25} 350 ${cx - 22} 410 ${cx - 20} 446 ` +
    `C${cx - 20} 456 ${cx - 8} 456 ${cx - 7} 448 ` +
    `C${cx - 5} 410 ${cx - 6} 350 ${cx - 4} 314 ` +
    `C${cx - 3} 270 ${cx - 3} 230 ${cx - 3} 198 Z`

  // القدم اليسرى.
  const footL = `M${cx - 20} 446 C${cx - 23} 458 ${cx - 22} 466 ${cx - 13} 466 C${cx - 5} 466 ${cx - 6} 456 ${cx - 7} 448 Z`

  const base = [head, neck, torso, ...pair(armL), ...pair(handL), ...pair(legL), ...pair(footL)]

  // العرض الخلفي يطابق الصورة الظلّية نفسها.
  return view === 'front' ? base : base
}

// ============================================================================
// إزاحة الأطراف حسب الجنس — كي تنطبق عضلات الذراع/الساق على الهيكل المتغيّر.
// ARM_DX = كتف الذكر − كتف الجنس (أكتاف أضيق ⇒ عضلات الذراع تنزاح للداخل).
// LEG_DX = ورك الذكر − ورك الجنس (ورك أوسع ⇒ عضلات الساق تنزاح للخارج).
// تُبقي مسارات العضلات (المرسومة بإحداثيات الذكر) منطبقة على كل جنس.
// ============================================================================

const ARM_DX: Record<Gender, number> = { male: 0, female: 9, unspecified: 5 }
const LEG_DX: Record<Gender, number> = { male: 0, female: -4, unspecified: 0 }

/** يزيح مسارًا أفقيًا بمقدار dx (يدعم نفس أوامر mirrorPath). */
function translateX(d: string, dx: number): string {
  if (dx === 0) return d
  const tokens = d.match(/[a-zA-Z]|-?\d*\.?\d+/g) ?? []
  const out: string[] = []
  let i = 0
  for (const tok of tokens) {
    if (/[a-zA-Z]/.test(tok)) {
      out.push(tok)
      i = 0
      continue
    }
    out.push(i % 2 === 0 ? String(parseFloat(tok) + dx) : tok)
    i++
  }
  let res = ''
  for (const t of out) res += /[a-zA-Z]/.test(t) ? (res ? ' ' : '') + t : ' ' + t
  return res.trim()
}

/** زوج يسار/يمين بعد إزاحة الجانب الأيسر بمقدار dx. */
const shiftedPair = (left: string, dx: number): string[] => {
  const s = translateX(left, dx)
  return [s, mirrorPath(s)]
}

