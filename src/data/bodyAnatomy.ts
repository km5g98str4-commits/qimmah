export interface Garment {
  d: string
  /** صلب = حشوة أعلى (حزام/حدود)، شفّاف = حشوة جزئية تُظهر العضلة. */
  opacity: number
}

/** يبني طبقة اللباس حسب الجنس وجهة العرض. */
