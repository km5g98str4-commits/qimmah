/** يبني كتل «السِكس باك» — ستّة كتل علوية/وسطى + عمودين سفليين. */
function buildAbs(cx: number): string[] {
  const blocks: string[] = []
  // صفّان علويّان (كتلتان لكل صف) + صف سفليّ مطاول.
  const rows = [
    { y: 134, h: 13, w: 10 }, // علوي
    { y: 149, h: 13, w: 11 }, // أوسط
  ]
  for (const r of rows) {
    // العمود الأيسر ثم عكسه للأيمن.
    const lx = cx - 2 - r.w
    blocks.push(rrect(lx, r.y, r.w, r.h, 3), mirrorPath(rrect(lx, r.y, r.w, r.h, 3)))
  }
  // الصف السفليّ — كتلتان أطول تنحدران نحو أسفل السرّة.
  const bl = `M${cx - 11} 163 L${cx - 2} 163 C${cx - 2} 175 ${cx - 4} 182 ${cx - 9} 184 C${cx - 12} 183 ${cx - 13} 178 ${cx - 12} 168 C${cx - 12} 165 ${cx - 12} 164 ${cx - 11} 163 Z`
  blocks.push(bl, mirrorPath(bl))
  return blocks
}

/** مسار مستطيل بزوايا دائرية (يدعم أوامر M L Q Z التي يعكسها mirrorPath). */
function rrect(x: number, y: number, w: number, h: number, r: number): string {
  const x1 = x + w
  const y1 = y + h
  return (
    `M${x + r} ${y} L${x1 - r} ${y} Q${x1} ${y} ${x1} ${y + r} ` +
    `L${x1} ${y1 - r} Q${x1} ${y1} ${x1 - r} ${y1} ` +
    `L${x + r} ${y1} Q${x} ${y1} ${x} ${y1 - r} ` +
    `L${x} ${y + r} Q${x} ${y} ${x + r} ${y} Z`
  )
}

