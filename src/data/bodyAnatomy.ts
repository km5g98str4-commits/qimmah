// ============================================================================
// تشريح الجسم — أشكال SVG لجسم بشري واقعي (أمامي/خلفي) قابل للتخصيص حسب الجنس.
// الإحداثيات على لوحة 0 0 220 470، مركز الجسم أفقيًا x=110.
// كل عضلة مرسومة كمسار/مسارات (paths) بمنحنيات تشريحية — لا أشكال بيضاوية مجرّدة.
// الجوانب اليسرى تُرسم يدويًا وتُعكس آليًا (mirrorPath) لإنتاج الجانب الأيمن،
// ما يضمن تماثلًا دقيقًا ويقلّل التكرار.
// ============================================================================

/** محور التماثل الأفقي (مركز×2): العكس x' = 220 − x. */
const AXIS2 = 220

/**
 * يعكس مسار SVG أفقيًا حول مركز اللوحة.
 * يدعم فقط الأوامر المطلقة M L C Q T S Z (إحداثيات أزواج x,y) — تُقلب قيم x.
 */
export function mirrorPath(d: string): string {
  const tokens = d.match(/[a-zA-Z]|-?\d*\.?\d+/g) ?? []
  const out: string[] = []
  let coordIndex = 0
  for (const tok of tokens) {
    if (/[a-zA-Z]/.test(tok)) {
      out.push(tok)
      coordIndex = 0 // كل أمر يبدأ سلسلة أزواج (x,y) جديدة
      continue
    }
    const n = parseFloat(tok)
    // الفهرس الزوجي = x فيُعكس، الفردي = y فيبقى.
    out.push(coordIndex % 2 === 0 ? String(AXIS2 - n) : String(n))
    coordIndex++
  }
  // إعادة تجميع: حرف ثم أرقامه مفصولة بمسافات.
  let res = ''
  for (const t of out) {
    if (/[a-zA-Z]/.test(t)) res += (res ? ' ' : '') + t
    else res += ' ' + t
  }
  return res.trim()
}

/** عضلة قابلة للاختيار = معرّفها + مسار/مسارات رسمها. */
export interface BodyRegion {
  m: MuscleId
  d: string[]
}

/** زوج يسار/يمين من مسار الجانب الأيسر. */
const pair = (left: string): string[] => [left, mirrorPath(left)]

// ============================================================================
// الأجزاء المحايدة (الهيكل الجلدي): رأس/رقبة/جذع/ذراعان/ساقان/يدان/قدمان.
// تُرسم بلون البشرة خلف العضلات لتعطي الجسم حدوده. تتغيّر أبعادها حسب الجنس.
// ============================================================================

interface Proportions {
  shoulder: number // نصف عرض الكتف
  waist: number // نصف عرض الخصر
  hip: number // نصف عرض الورك
  neck: number // نصف عرض الرقبة
}

const PROPS: Record<Gender, Proportions> = {
  // ذكر: أكتاف عريضة، خصر متوسط (مظهر V رياضي).
  male: { shoulder: 50, waist: 27, hip: 31, neck: 11 },
  // أنثى: أكتاف أضيق، خصر منحوت، ورك أوسع (مظهر رياضي أنثوي).
  female: { shoulder: 41, waist: 21, hip: 35, neck: 9 },
  // غير محدّد: وسط بين الاثنين.
  unspecified: { shoulder: 45, waist: 24, hip: 31, neck: 10 },
}

/** يبني مسارات الهيكل الجلدي المحايد لجهة العرض. */
export function buildSilhouette(gender: Gender, view: MuscleView): string[] {
  const p = PROPS[gender]
  const cx = 110
  const sh = p.shoulder
  const w = p.waist
  const hip = p.hip
  const nk = p.neck

  // الرأس + الرقبة (مشتركة بين الجهتين).
  const head = `M${cx} 14 C${cx - 17} 14 ${cx - 20} 34 ${cx - 17} 46 C${cx - 14} 56 ${cx - 7} 60 ${cx} 60 C${cx + 7} 60 ${cx + 14} 56 ${cx + 17} 46 C${cx + 20} 34 ${cx + 17} 14 ${cx} 14 Z`
  const neck = `M${cx - nk} 56 L${cx + nk} 56 L${cx + nk + 1} 72 L${cx - nk - 1} 72 Z`

  // الجذع: من الكتف إلى الورك بمنحنى خصر.
  const torso =
    `M${cx - sh} 80 ` +
    `C${cx - sh - 3} 104 ${cx - w - 4} 132 ${cx - w} 152 ` +
    `C${cx - w + 1} 170 ${cx - hip} 178 ${cx - hip} 190 ` +
    `L${cx + hip} 190 ` +
    `C${cx + hip} 178 ${cx + w - 1} 170 ${cx + w} 152 ` +
    `C${cx + w + 4} 132 ${cx + sh + 3} 104 ${cx + sh} 80 ` +
    `C${cx + sh - 8} 70 ${cx - sh + 8} 70 ${cx - sh} 80 Z`

  // الذراع الأيسر: من الكتف لأسفل الساعد (يُعكس للأيمن).
  const armL =
    `M${cx - sh + 3} 82 ` +
    `C${cx - sh - 8} 98 ${cx - sh - 9} 142 ${cx - sh - 5} 182 ` +
    `C${cx - sh - 4} 192 ${cx - sh + 8} 192 ${cx - sh + 11} 184 ` +
    `C${cx - sh + 15} 146 ${cx - sh + 13} 100 ${cx - sh + 9} 84 Z`

  // اليد الأيسر (كتلة بسيطة عند نهاية الساعد).
  const handL = `M${cx - sh - 5} 184 C${cx - sh - 9} 188 ${cx - sh - 8} 202 ${cx - sh - 2} 204 C${cx - sh + 6} 205 ${cx - sh + 12} 198 ${cx - sh + 11} 188 Z`

  // الساق اليسرى: فخذ ثم ساق سفلية، من الورك للكاحل.
  const legL =
    `M${cx - hip} 188 ` +
    `C${cx - hip - 1} 232 ${cx - hip + 4} 286 ${cx - 24} 312 ` +
    `C${cx - 25} 350 ${cx - 22} 404 ${cx - 21} 438 ` +
    `C${cx - 21} 448 ${cx - 9} 448 ${cx - 8} 440 ` +
    `C${cx - 6} 404 ${cx - 7} 350 ${cx - 5} 314 ` +
    `C${cx - 4} 270 ${cx - 4} 220 ${cx - 4} 192 Z`

  // القدم اليسرى.
  const footL = `M${cx - 21} 438 C${cx - 23} 450 ${cx - 22} 458 ${cx - 14} 458 C${cx - 6} 458 ${cx - 7} 448 ${cx - 8} 440 Z`

  const base = [head, neck, torso, ...pair(armL), ...pair(handL), ...pair(legL), ...pair(footL)]

  // العرض الخلفي يطابق الهيكل (الظهر بنفس الصورة الظلّية).
  return view === 'front' ? base : base
}

