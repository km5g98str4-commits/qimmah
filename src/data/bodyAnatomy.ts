// الملابس الرياضية المحتشمة — طبقة تُرسم فوق العضلات، شفّافة جزئيًا كي يظهر
// تلوين العضلة المُدرَّبة من خلالها، مع حدّ وحزام واضحين يؤكّدان اللباس.
//  • الذكر/المحايد: شورت طويل يغطّي من فوق السرّة إلى الركبة.
