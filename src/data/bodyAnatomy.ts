  const cx = CX
  const p = PROPS[gender]
  const hip = p.hip
  const items: Garment[] = []

  // شورت طويل إلى الركبة (مشترك للجميع) — يغطّي من فوق السرّة حتى الركبة.
  // الوسط عند y≈150 (فوق السرّة)، والحاشية عند y≈316 (الركبة).
