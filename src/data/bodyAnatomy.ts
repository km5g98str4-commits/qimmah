// ============================================================================
// الملابس الرياضية المحتشمة — طبقة تُرسم فوق العضلات.
// شفافة جزئيًا كي يظهر تلوين العضلة المُدرَّبة من خلالها، مع حدود واضحة.
// شورت يغطّي حتى الركبة (y≈300) وحزامه يستر السرّة (y≈150).
// للأنثى: توب رياضي يستر الصدر والوسط بالكامل + الشورت نفسه.
// ============================================================================

export interface Garment {
  d: string
  /** صلب = حشوة كاملة، شفّاف = حشوة جزئية تُظهر العضلة. */
  opacity: number
}

/** شورت رياضي يصل الركبة، يستر حزامه السرّة. أمامي/خلفي. */
function shorts(p: Proportions, view: MuscleView): Garment {
  const cx = 110
  const hip = p.hip
  const w = p.waist
  if (view === 'front') {
    return {
      d:
        `M${cx - w - 2} 150 ` +
        `C${cx - hip - 1} 158 ${cx - hip + 3} 230 ${cx - 26} 298 ` +
        `L${cx - 7} 300 L${cx - 3} 214 L${cx} 210 L${cx + 3} 214 L${cx + 7} 300 ` +
        `L${cx + 26} 298 ` +
        `C${cx + hip - 3} 230 ${cx + hip + 1} 158 ${cx + w + 2} 150 ` +
        `C${cx + 14} 145 ${cx - 14} 145 ${cx - w - 2} 150 Z`,
      opacity: 0.5,
    }
  }
  // خلفي: يغطّي الألوية بالكامل (شقّ المنتصف أعلى).
  return {
    d:
      `M${cx - w - 2} 150 ` +
      `C${cx - hip - 1} 158 ${cx - hip + 3} 232 ${cx - 26} 300 ` +
      `L${cx - 6} 302 L${cx} 250 L${cx + 6} 302 ` +
      `L${cx + 26} 300 ` +
      `C${cx + hip - 3} 232 ${cx + hip + 1} 158 ${cx + w + 2} 150 ` +
      `C${cx + 14} 145 ${cx - 14} 145 ${cx - w - 2} 150 Z`,
    opacity: 0.55,
  }
}

/** يبني طبقة اللباس حسب الجنس وجهة العرض. */
export function buildClothing(gender: Gender, view: MuscleView): Garment[] {
  const cx = 110
  const p = PROPS[gender]
  const items: Garment[] = []

  if (gender === 'female') {
    if (view === 'front') {
      // توب رياضي يستر الصدر والوسط بالكامل بحياء، بحمّالتين.
      items.push({
        d:
          `M${cx - 30} 82 ` +
          `C${cx - 33} 102 ${cx - 30} 132 ${cx - 23} 150 ` +
          `C${cx - 11} 156 ${cx + 11} 156 ${cx + 23} 150 ` +
          `C${cx + 30} 132 ${cx + 33} 102 ${cx + 30} 82 ` +
          `C${cx + 16} 90 ${cx - 16} 90 ${cx - 30} 82 Z`,
        opacity: 0.58,
      })
      items.push({ d: `M${cx - 26} 82 L${cx - 18} 77 L${cx - 14} 92 L${cx - 22} 96 Z`, opacity: 0.58 })
      items.push({ d: `M${cx + 26} 82 L${cx + 18} 77 L${cx + 14} 92 L${cx + 22} 96 Z`, opacity: 0.58 })
    } else {
      // ظهر التوب الرياضي + حمّالتان متقاطعتان.
      items.push({
        d:
          `M${cx - 30} 82 ` +
          `C${cx - 33} 102 ${cx - 30} 130 ${cx - 23} 148 ` +
          `C${cx - 11} 154 ${cx + 11} 154 ${cx + 23} 148 ` +
          `C${cx + 30} 130 ${cx + 33} 102 ${cx + 30} 82 ` +
          `C${cx + 16} 90 ${cx - 16} 90 ${cx - 30} 82 Z`,
        opacity: 0.58,
      })
      items.push({ d: `M${cx - 22} 86 L${cx + 18} 104 L${cx + 14} 110 L${cx - 25} 92 Z`, opacity: 0.5 })
      items.push({ d: `M${cx + 22} 86 L${cx - 18} 104 L${cx - 14} 110 L${cx + 25} 92 Z`, opacity: 0.5 })
    }
    // شورت ساتر يصل الركبة (نفس الذكر) — يستر الورك/الفخذ حتى الركبة.
    items.push(shorts(p, view))
    return items
  }

  // الذكر / غير المحدّد: جذع عضلي مكشوف كخريطة تشريح + شورت يصل الركبة يستر السرّة.
  items.push(shorts(p, view))
  return items
}
