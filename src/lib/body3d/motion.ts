// تكامل حركة المجسّم — معزول عن React كي يكون قابلًا للاختبار والإثبات.
//
// المشكلة التي يحلّها هذا الملف: الانزلاق بعد رفع الإصبع كان يُضاف إلى الزاوية
// **لكل إطار** بلا ضرب في الزمن (`yaw += vyaw`)، بينما التخامد كان زمنيًا صحيحًا.
// النتيجة: على شاشة ProMotion بـ١٢٠هرتز يدور الجسم ضِعف ما يدور على ٦٠هرتز
// من نفس الحركة — وهذا هو جهاز المنتج المستهدف (iPhone).
//
// وبالمثل كانت سرعة القذف تُؤخذ من إزاحة آخر حدث مؤشّر وحدها، فتضعف إلى النصف
// حين يرسل النظام أحداثًا بمعدّل ١٢٠هرتز لأن إزاحة كل حدث تصير نصفًا.
//
// الحل: التعبير عن السرعة بوحدة «راديان لكل إطار مرجعي ٦٠هرتز» وضربها في
// (dt × ٦٠) عند التكامل — فتتطابق الحركة على أي معدّل إطارات أو أحداث.
// ============================================================================

/** معدّل الإطارات المرجعي الذي عوير عليه إحساس الحركة أصلًا. */
export const REF_FPS = 60

/** أقل سرعة زاوية تستحقّ إطارًا جديدًا (راديان/إطار مرجعي). */
export const GLIDE_EPSILON = 0.0006

/** نسبة ما يتبقّى من السرعة بعد ثانية واحدة — تخامد أُسّي. */
const GLIDE_DECAY_PER_SEC = 0.02

/** لوغاريتم معامل التخامد — يلزم للتكامل المضبوط أدناه. */
const DECAY_LN = Math.log(GLIDE_DECAY_PER_SEC)

/** حدّ زمني لفارق أحداث المؤشّر (م.ث) — يمنع القسمة على فارق شاذ. */
const MIN_POINTER_DT = 4
const MAX_POINTER_DT = 32

/**
 * يحوّل إزاحة مؤشّر خام إلى سرعة زاوية مستقلّة عن معدّل أحداث المؤشّر.
 *
 * @param deltaRad الزاوية التي قطعها هذا الحدث (راديان).
 * @param dtMs الزمن منذ حدث المؤشّر السابق (م.ث)؛ 0 عند أوّل حدث.
 * @returns السرعة بوحدة راديان لكل إطار مرجعي ٦٠هرتز.
 */
export function pointerVelocity(deltaRad: number, dtMs: number): number {
  if (!Number.isFinite(dtMs) || dtMs <= 0) return deltaRad
  const dt = Math.min(MAX_POINTER_DT, Math.max(MIN_POINTER_DT, dtMs))
  return (deltaRad * (1000 / REF_FPS)) / dt
}

/** نتيجة خطوة انزلاق واحدة. */
export interface GlideStep {
  /** الزيادة على الزاوية خلال هذه الخطوة (راديان). */
  dYaw: number
  /** السرعة بعد التخامد. */
  velocity: number
  /** هل ما زالت الحركة مستمرّة؟ */
  moving: boolean
}

/**
 * يقدّم الانزلاق خطوة زمنية واحدة — النتيجة مستقلّة عن معدّل الإطارات.
 *
 * السرعة تتخامد أُسّيًا، فضرب السرعة الابتدائية في طول الخطوة (أويلر الأمامي)
 * يبالغ في المسافة كلّما طالت الخطوة — أي يدور الجسم مسافة مختلفة على ٦٠هرتز
 * عنها على ١٢٠هرتز. نستخدم التكامل المضبوط ∫v₀·k^t dt = v₀·(k^dt−1)/ln k
 * فتتطابق المسافة على أي معدّل إطارات بدل أن تتقارب فقط.
 *
 * @param velocity السرعة الحالية (راديان/إطار مرجعي).
 * @param dt طول الخطوة بالثواني.
 */
export function advanceGlide(velocity: number, dt: number): GlideStep {
  if (Math.abs(velocity) <= GLIDE_EPSILON || dt <= 0) {
    return { dYaw: 0, velocity: 0, moving: false }
  }
  const decay = Math.pow(GLIDE_DECAY_PER_SEC, dt)
  const next = velocity * decay
  return {
    dYaw: (velocity * REF_FPS * (decay - 1)) / DECAY_LN,
    velocity: next,
    moving: Math.abs(next) > GLIDE_EPSILON,
  }
}
