/** أقصى صيغ جسرية لاستعلام واحد — سقف معلَن يمنع انفجار الطلبات. */
export const MAX_BRIDGE_VARIANTS = 1

/** رمز لاتيني/رقمي: لا يحتاج جسرًا، يمرّ كما هو. */
const LATIN_OR_DIGIT = /^[a-z0-9'&.+-]+$/

/**
 * خريطة مبنيّة مرّة: **الرمز العربي المطبَّع ⇒ الصيغة اللاتينية**.
 *
 * تُبنى من القائمتين معًا لأن قاعدة «كل الرموز أو لا شيء» تحتاجهما في جدول واحد،
 * والتطبيع يمرّ بـ`normalizeProductKey` — **نفس** المطبِّع الذي يقيس به البحث،
 * لا نسخة ثانية تتباعد عنه (نفس حجّة `brandFallbackIds`).
 *
 * الأسماء متعدّدة الكلمات («كوكا كولا» · «كيت كات» · «سفن اب») تُدخَل بمفتاح
 * الجملة كاملةً أيضًا، فيُجرَّب الاستعلام كلّه قبل تفكيكه رمزًا رمزًا.
 */
function buildMap(groups: readonly (readonly string[])[]): ReadonlyMap<string, string> {
  const map = new Map<string, string>()
  for (const [canonical, ...variants] of groups) {
    for (const v of variants) {
      const key = normalizeProductKey(v)
      if (key && !map.has(key)) map.set(key, canonical)
    }
  }
  return map
}

const ALIAS_MAP: ReadonlyMap<string, string> = buildMap([...BRAND_SCRIPT_ALIASES, ...PACK_WORD_ALIASES])

/**
 * الصيغة الجسرية للاستعلام — أو `null` حين لا تنطبق القاعدة.
 *
 * الترتيب: تُجرَّب **الجملة كاملةً** أولًا (فتلتقط «كوكا كولا» و«كيت كات» بلا
 * تفكيك)، ثم رمزًا رمزًا بشرط أن **يُترجَم كل رمز أو يكون لاتينيًّا أصلًا**.
 * ويُردّ `null` إن لم يتغيّر شيء — فلا تُضاف صيغة مكرّرة بلا فائدة.
 */
export function brandBridgeVariant(rawQuery: string): string | null {
  const q = normalizeProductKey(rawQuery)
  if (!q) return null

  const whole = ALIAS_MAP.get(q)
  if (whole) return whole

  const tokens = q.split(' ').filter(Boolean)
  if (tokens.length === 0) return null

  const out: string[] = []
  let bridged = false
  for (const token of tokens) {
    const mapped = ALIAS_MAP.get(token)
    if (mapped) {
      out.push(mapped)
      bridged = true
      continue
    }
    // رمز لاتيني/رقمي يمرّ كما هو؛ وأي رمز عربي بلا مقابل **يُسقط الصيغة كلّها**.
    if (!LATIN_OR_DIGIT.test(token)) return null
    out.push(token)
  }
  if (!bridged) return null

  const value = out.join(' ').trim()
  return value && value !== q ? value : null
}
