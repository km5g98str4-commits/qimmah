/** خريطة مبنيّة مرّة: كتابة العلامة ⇒ معرّفات الأصناف العامّة. */
const ALIAS_TO_IDS: ReadonlyMap<string, readonly string[]> = new Map(
  BRAND_GENERIC_FALLBACKS.flatMap((b) => b.aliases.map((a) => [a, b.genericIds] as const)),
)

/**
 * معرّفات الأصناف العامّة لعلامة كُتبت في الاستعلام.
 *
 * **المطابقة تامّة على الاستعلام المطبَّع كلّه** لا بادئة ولا تضمين: البادئة تجعل
 * «كو» تستدعي الكولا، والتضمين يجعل أي جملة تحوي «صافي» تستدعي الألبان. والمطبِّع
 * يُمرَّر من الخارج كي يبقى **نفس** المطبِّع الذي يقيس به البحث — لا نسخة ثانية.
 */
export function brandFallbackIds(query: string, normalize: (s: string) => string): readonly string[] {
  const q = normalize(query)
  if (!q) return []
  for (const [alias, ids] of ALIAS_TO_IDS) {
    if (normalize(alias) === q) return ids
  }
  return []
}
