/**
 * تغطية العلامات التجارية — **بديل عام صادق، لا ماكروز مخترعة**.
 *
 * ═══ المشكلة التي يحلّها ═══
 * المستخدم السعودي يكتب اسم علامة («كوكاكولا» · «الصافي» · «لوزين»)، ونحن لا نملك
 * لكل علامة قيمًا غذائية من مصدر يمكن الدفاع عنه. والطريقان الخاطئان معروفان:
 *   ١. **اختراع ماكروز** لمنتج العلامة — كذب مباشر على رقمٍ يبني عليه المستخدم يومه.
 *   ٢. **صفر نتيجة** — فيغلق المستخدم الشاشة ولا يسجّل شيئًا.
 *
 * والطريق الثالث هو هذا الملف: من كتب علامةً بلا منتج مصدَّق يرى **الصنف العام**
 * المطابق فئتها — «مشروب غازي» لا «كوكاكولا زيرو ٣٣٠مل». الاسم المعروض هو اسم
 * الصنف العام كما هو، فلا يُنسب رقمٌ إلى علامة لم يأتِ منها (§5 الصدق).
 *
 * ═══ حدّه الصارم ═══
 * • البديل **أضعف رتبة في القائمة كلّها** (`BRAND_FALLBACK_STRENGTH`) — يظهر بعد
 *   كل مطابقة حقيقية، منسَّقة كانت أو معبّأة. فمنتج العلامة الحقيقي من الكتالوج
 *   المعبّأ (بقيمه المصدَّقة) **يسبقه دائمًا**، وهذا هو الصواب.
 * • لا يُضاف صنف عام إلى القائمة إن كان حاضرًا فيها أصلًا.
 * • الخريطة **لا تحمل اسم العلامة إلى الواجهة** — تُقرأ من الاستعلام ولا تُكتب في
 *   أي نصّ معروض.
 */

