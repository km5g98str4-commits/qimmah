// ═══ العطل الذي أنشأ هذا الملف ═══
// `supabaseClient` يحمل عنوان مشروع الإنتاج ومفتاح anon **مخبوزين كاحتياط**،
// و`isSupabaseConfigured()` تعيد `true` بمجرّد وجودهما. ولأن كل كاتب خطير
// يسأل هذا السؤال وحده (`start_trial` · `redeem_access_code` ·
// `claim_pending_grants` · `signUp` · مزامنة الملفات)، فإن **أي بناء بلا
// متغيّرات بيئة يتكلّم مع قاعدة الإنتاج** — بما فيه نشرة معاينة لمراجعة يدوية.
//
// أي أن مراجعة المؤسس كانت قادرة على: بدء تجربة حقيقية · استهلاك كود تفعيل
// حقيقي · إنشاء مستخدم إنتاج · إرسال بريد إنتاج. لا بقصد، بل لأن غياب الضبط
// كان يعني «استعمل الإنتاج» بدل «لا تستعمل شيئًا».
//
// وتعليقات المصدر كانت تصف السلوك **الصحيح** («بلا ضبط Supabase تبقى الإجابة
// `none` بصدق») — وهي صادقة يوم كُتبت، وبطلت يوم أُضيف الاحتياط المخبوز دون
// إعادة النظر فيها. فالخلل تعارض بين طبقتين، لا خطأ في أيّهما منفردة.
//
// ═══ لماذا هنا وحده ═══
// لا معمارية ثانية ولا منطق مكرَّر: كل الكتّاب الخطرين يمرّون بـ
// `isSupabaseConfigured()`، وكلٌّ منهم **يفشل مغلقًا أصلًا** بحالة صادقة قائمة
// (`offline` للاستبدال · `none` للاستحقاق · وضع الضيف للحساب). فيكفي أن نجعل
// الجواب `false` في المعاينة، وتستيقظ تلك الحالات كما كُتبت.

/** بيئات التشغيل المعلَنة. الغياب = إنتاج (سلوك اليوم بلا تغيير). */
export type AppEnv = 'production' | 'founder_preview'

/**
 * البيئة الفعّالة — **قرار وقت بناء لا وقت تشغيل**.
 *
 * `import.meta.env` يُستبدَل نصيًّا عند البناء، فالقيمة تُخبَز في الحزمة ولا
 * سبيل لتغييرها من المتصفّح: لا عنوان URL ولا `localStorage` ولا
 * `sessionStorage` يملك تبديلها. وهذا شرط أمني لا تفصيل تنفيذي — لو قُرئت من
 * مصدر يملكه المستخدم لصار «وضع الإنتاج» خيارًا لمن يريده.
 */
export const APP_ENV: AppEnv =
  import.meta.env.VITE_APP_ENV === 'founder_preview' ? 'founder_preview' : 'production'

/** هل هذا بناء مراجعة المؤسس؟ */
export function isFounderPreview(): boolean {
  return APP_ENV === 'founder_preview'
}

