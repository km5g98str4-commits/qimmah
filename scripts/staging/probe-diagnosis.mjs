// تصنيف تأكيد البريد — ثلاثة، لا اثنان
// ============================================================================
// ⚠️ **«لا أعرف» ليست «فشل».** أوّل صيغةٍ كانت ثنائية: إمّا `mailer_autoconfirm
// === false` فنجاح، وإلا فشل. فغاب الحقل عن الناتج الحقيقي — وهو غيابٌ يعني
// **تعذّر المعرفة**، لا خللًا في الإعداد — فخرج المسبار بالرمز ١ بينما كانت
// **خمسة عشر رفضًا قد مرّت كلّها**. أي أن سطرًا معلوماتيًّا واحدًا وسم نتيجةً
// ناجحة بالفشل.
//
// وهذا نفس العيب الذي أُصلح في الضابط الموجب قبله بساعة — **وأُعيد ارتكابه في
// نفس الالتزام**، في السطر الذي أُضيف بعده مباشرةً. فيُكتب هنا بالاسم.
//
// والثلاثة مقصودة:
//   ENABLED   — التأكيد مطلوب ⇒ نموذج الوصول يعمل.
//   DISABLED  — التأكيد مُعطَّل ⇒ **فشلٌ حقيقي**: كل مسار يشترط
//               `email_confirmed_at` سينكسر.
//   UNKNOWN   — الحقل غائب ⇒ يُبلَّغ ولا يُسقِط، ومعه مفاتيح الناتج كي
//               تُقرأ العلّة من بيانات لا من تخمين.
// ============================================================================

/**
 * @param {unknown} settings ناتج `/auth/v1/settings` محلَّلًا.
 * @returns {'ENABLED'|'DISABLED'|'UNKNOWN'}
 */
export function classifyConfirmEmail(settings) {
  if (!settings || typeof settings !== 'object') return 'UNKNOWN'
  const v = /** @type {Record<string, unknown>} */ (settings).mailer_autoconfirm
  if (v === false) return 'ENABLED'
  if (v === true) return 'DISABLED'
  return 'UNKNOWN'
}

