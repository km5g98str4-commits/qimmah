// ============================================================================
// ═══ لماذا وحدةٌ مستقلّة ═══
// المسبار يتوقّف حين لا يفرّق بين مسموحٍ وممنوع، ويجب أن **يُفيد** عند توقّفه:
// أن يقول ماذا رأى بدل أن يترك القارئ يخمّن. وحكمُه هذا يحتاج إثباتًا — لأنه
// حكمٌ منطقي على جدول أرقام، ويمكن أن يخطئ **بلا أن يظهر خطؤه في أي تشغيل**.
//
// ولو نُسخت الشجرة في الإثبات لصارت نسخةً تشيخ: يُعدَّل الحكم في المسبار ولا
// يُعدَّل في نسخته، فيُصادق الإثبات على منطقٍ لم يعد موجودًا. وذلك عين العطل
// الذي تكرّر في هذه الموجة أربع مرّات. فالسلطة واحدة، والطرفان يستوردان.
//
// ⚠️ **والـ401 دليلُ وصول لا دليلَ انقطاع.** أوّل صيغةٍ اشترطت حالةً `< 400`
// لإثبات أن الشبكة بلغت Supabase — فسقطت **الحالة المرصودة فعلًا على staging**
// (كل النقاط 401) في «غير مصنَّفة»، وهي أهمّ حالة على الإطلاق. كشفتها محاكاةٌ
// بجداول مصنوعة، لا تشغيلٌ حيّ: التشغيل من بيئتنا محجوب أصلًا فلا يبلغها.
// ============================================================================

/**
 * @param {{path:string, ok:number, bad:number}[]} table
 *   لكل نقطة: حالتها بمفتاح صحيح (`ok`) وبمفتاح مهشَّم (`bad`).
 * @returns {'PROXY'|'KEY_REJECTED'|'WIDE_OPEN'|'UNCLASSIFIED'}
 */
export function diagnose(table) {
  if (!Array.isArray(table) || table.length === 0) return 'UNCLASSIFIED'
  // وكيلٌ أو جدار: يردّ 403 عند النفق قبل أن يبلغ الطلبُ Supabase أصلًا،
  // فيتساوى المفتاحان لأن أحدًا لم يقرأهما.
  if (table.every((r) => r.ok === 403 && r.bad === 403)) return 'PROXY'
  // 401 لا تصدر إلا عن Supabase — فوجودها على **مفتاح صحيح** يعني: وصلنا، ورُدّ.
  if (table.some((r) => r.ok === 401)) return 'KEY_REJECTED'
  // يستجيب لمفتاحٍ مهشَّم كما يستجيب للصحيح ⇒ لا حراسة أصلًا.
  if (table.every((r) => r.ok === 200 && r.bad === 200)) return 'WIDE_OPEN'
  return 'UNCLASSIFIED'
}

