#!/usr/bin/env node
// ============================================================================
// إثبات شجرة قرار المسبار — [STAGING-COMMISSIONING]
// ============================================================================
// المسبار يتوقّف حين يعمى، وحكمُه عند التوقّف هو **كل** ما يخرج به المشغّل.
// وهو حكمٌ منطقي على جدول أرقام: يمكن أن يخطئ **بلا أن يظهر خطؤه في أي
// تشغيل** — فبيئتنا محجوبة عن Supabase أصلًا، فلا تبلغ إلا فرعًا واحدًا منه.
//
// ⚠️ **وهذا ليس فرضًا نظريًّا:** أوّل صيغة صنّفت **الحالة المرصودة فعلًا على
// staging** — كل النقاط 401 — «غير مصنَّفة»، وهي أهمّ حالة على الإطلاق: تعني
// أن المفتاح مرفوض وأن بناء التطبيق لن يصادق. كشفتها هذه الجداول المصنوعة،
// ولم يكن ليكشفها تشغيلٌ حيّ من عندنا أبدًا.
//
// ⚠️ **ولا تُنسخ الشجرة هنا** — تُستورد. النسخة تشيخ فيُصادق الإثبات على منطق
// لم يعد موجودًا، وهو عين العطل الذي تكرّر في هذه الموجة.
// ============================================================================
import { diagnose, EXPLAIN } from './probe-diagnosis.mjs'

let pass = 0
const fails = []
const check = (l, c, d = '') => {
  if (c) { pass += 1; console.log(`  ✓ ${l}${d ? `  — ${d}` : ''}`) }
  else { fails.push(l); console.log(`  ✗ FAIL: ${l}${d ? `  — ${d}` : ''}`) }
}

console.log('\n══ شجرة قرار المسبار الأعمى ══')

const T = (...triples) => triples.map(([p, ok, bad]) => ({ path: p, ok, bad }))
const CASES = [
  ['وكيل يحجب: كل نقطة 403 بالمفتاحين',
   T(['/auth/v1/health', 403, 403], ['/auth/v1/settings', 403, 403], ['/rest/v1/', 403, 403]), 'PROXY'],
  ['★ الحالة المرصودة على staging: كل نقطة 401',
   T(['/auth/v1/health', 401, 401], ['/auth/v1/settings', 401, 401], ['/rest/v1/', 401, 401]), 'KEY_REJECTED'],
  ['الصحّة تعمل بلا مفتاح والبقيّة تُردّ',
   T(['/auth/v1/health', 200, 200], ['/auth/v1/settings', 401, 401], ['/rest/v1/', 401, 401]), 'KEY_REJECTED'],
  ['يستجيب لمفتاحٍ مهشَّم كما للصحيح',
   T(['/auth/v1/health', 200, 200], ['/auth/v1/settings', 200, 200], ['/rest/v1/', 200, 200]), 'WIDE_OPEN'],
  ['أعطال خادم — لا تُصنَّف تخمينًا',
   T(['/auth/v1/health', 500, 500], ['/auth/v1/settings', 503, 503], ['/rest/v1/', 502, 502]), 'UNCLASSIFIED'],
  ['جدول فارغ — لا حكم بلا بيانات', [], 'UNCLASSIFIED'],
]
for (const [name, table, want] of CASES) {
  const got = diagnose(table)
  check(name, got === want, got === want ? got : `جاء ${got} وتوقّعنا ${want}`)
}

// ⟲ **التأكيد المضادّ الأوّل:** الأحكام تختلف فعلًا. لو أعادت الشجرة حكمًا
//    واحدًا دائمًا لمرّت حالاتٌ عدّة أعلاه بالصدفة لا بالصواب.
const distinct = new Set(CASES.map(([, t]) => diagnose(t)))
check('⟲ والأحكام أربعة مميّزة لا حكمًا واحدًا يُرضي الجميع',
  distinct.size === 4, [...distinct].join(' · '))

// ⟲ **والثاني:** الـ403 والـ401 **لا تُخلطان**. اشتراطُ حالةٍ `< 400` لإثبات
//    الوصول هو العطل الذي وقع فعلًا — فيُحرَس بأن يختلف حكم الجدولين.
check('⟲ و403 الشاملة ≠ 401 الشاملة — والخلط بينهما هو العطل الذي وقع',
  diagnose(T(['/x', 403, 403])) !== diagnose(T(['/x', 401, 401])),
  `${diagnose(T(['/x', 403, 403]))} ≠ ${diagnose(T(['/x', 401, 401]))}`)

// ⟲ **والثالث:** لكل حكم شرحٌ عربيّ. حكمٌ بلا شرح يترك المشغّل بلا شيء —
//    وهو بالضبط العيب الذي أوجب هذا كلّه (توقّفٌ آمن بلا إفادة).
const missing = [...new Set(Object.keys(EXPLAIN))].filter((k) => !EXPLAIN[k]?.length)
const verdicts = ['PROXY', 'KEY_REJECTED', 'WIDE_OPEN', 'UNCLASSIFIED']
check('⟲ ولكل حكم شرحٌ غير فارغ — فالتوقّف الآمن يجب أن يكون مفيدًا',
  missing.length === 0 && verdicts.every((v) => EXPLAIN[v]?.length > 0),
  missing.join(', ') || `${verdicts.length} حكمًا مشروحًا`)

console.log(`\n${fails.length === 0 ? '✅' : '❌'} شجرة القرار: ${pass} فحصًا · ${fails.length} فشل`)
if (fails.length) { fails.forEach((f) => console.log(`   • ${f}`)); process.exit(1) }
